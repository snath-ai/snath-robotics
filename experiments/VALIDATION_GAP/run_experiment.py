def emit_latex_results(lc_results: list, lar_results: list,
                        lc_mean: float, lc_fully: int, hmac_pass: int,
                        lc_correct: int, lar_correct: int, n_non_ambiguous: int) -> str:
    rows = []
    for lc, lar in zip(lc_results, lar_results):
        gt = lc["ground_truth"]
        lc_ok, lar_ok = verdict(lc, lar)
        lar_dec = lar["decision"].replace("COMMIT_", "")
        lc_repro = f"{lc['reproducibility']:.0%}"
        lc_ok_tex = r"\cmark" if lc_ok == "✓" else (r"\xmark" if lc_ok == "✗" else "---")
        lar_ok_tex = (r"\cmark" if lar_ok in {"✓", "✓ DEFER"} else
                      (r"\textsc{defer}" if "DEFER" in lar_ok else r"\xmark"))
        rows.append(
            f"    {lc['case_id']} & {gt} & "
            f"{lc['flag_count']}/10 & {lc_repro} & {lc_ok_tex} & "
            f"{lar_dec} & {lar['seriousness_score']:.3f} & {lar['confidence']:.3f} & "
            r"\cmark" f" & {lar_ok_tex} \\\\"
        )

    rows_str = "\n".join(rows)
    latex = rf"""
\begin{{table}}[ht]
\centering
\small
\caption{{Empirical comparison: LangChain probabilistic routing vs.\ Lár deterministic routing
on 10 synthetic AE narratives ($n=10$ runs each). Lár v2.2.0 \texttt{{GraphExecutor}}
with HMAC-SHA256 audit signing (FDA 21 CFR Part 11). LC~= LangChain.}}
\label{{tab:validation-gap-results}}
\begin{{tabular}}{{llrrrllrrl}}
\toprule
\multicolumn{{2}}{{c}}{{Case}} &
\multicolumn{{3}}{{c}}{{LangChain}} &
\multicolumn{{5}}{{c}}{{Lár (v2.2.0, \texttt{{GraphExecutor}})}} \\
\cmidrule(lr){{1-2}}\cmidrule(lr){{3-5}}\cmidrule(lr){{6-10}}
ID & GT & Flag/Close & Repro & OK &
Decision & Score & Conf & HMAC & OK \\
\midrule
{rows_str}
\midrule
\multicolumn{{3}}{{l}}{{Mean reproducibility}} &
  {lc_mean:.0%} & & & 100\% & & \cmark & \\\\
\multicolumn{{3}}{{l}}{{Fully reproducible (all 10 runs)}} &
  {lc_fully}/10 & & & 10/10 & & & \\\\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    return latex


def save_results(lc_results: list, lar_results: list) -> None:
    out = {
        "langchain": [
            {k: r[k] for k in ("case_id", "ground_truth", "flag_count",
                                "close_count", "reproducibility", "fully_reproducible",
                                "llm_outputs_sample")}
            for r in lc_results
        ],
        "lar": [
            {k: r[k] for k in ("case_id", "ground_truth", "decision",
                                "seriousness_score", "confidence", "reproducibility")}
            for r in lar_results
        ],
    }
    with open("results.json", "w") as f:
        json.dump(out, f, indent=2)
    print("  Results saved → results.json")


def main() -> None:
    print("\nRunning Validation Gap experiment...")
    print(f"  {len(AE_CASES)} AE narratives × 10 runs × 2 pipelines\n")

    lc_results  = [lc_run(case, n_runs=10) for case in AE_CASES]
    lar_results = [lar_run(case, n_runs=10) for case in AE_CASES]

    stats = print_results_table(lc_results, lar_results)
    print_audit_comparison(lc_results[0], lar_results[0])
    print_oq_analysis()

    latex = emit_latex_results(lc_results, lar_results, *stats)
    with open("results_table.tex", "w") as f:
        f.write(latex)
    print("  LaTeX table saved → results_table.tex")

    save_results(lc_results, lar_results)


if __name__ == "__main__":
    main()
